import assert from 'node:assert/strict';

// Runs inside the migration suite's isolated database, using the actual novel
// review tables, reply constraints, and banned-account RLS installed there.
export async function checkCommentNotifications(db, apply, owner, reader) {
  const third = '00000000-0000-0000-0000-000000000003';
  await db.exec(`
    alter table public.reading_lists add column visibility text not null default 'private';
    create table public.friendships (
      user_id_1 uuid, user_id_2 uuid, status text
    );
    create table public.reading_list_reviews (
      id bigint generated by default as identity primary key,
      reading_list_id uuid references public.reading_lists(id),
      user_id uuid references auth.users(id), rating numeric, comment text,
      unique(reading_list_id, user_id)
    );
    create table public.reading_list_review_replies (
      id bigint generated by default as identity primary key,
      review_id bigint references public.reading_list_reviews(id),
      parent_reply_id bigint references public.reading_list_review_replies(id),
      user_id uuid references auth.users(id), comment text
    );
    alter table public.notifications enable row level security;
    create policy inbox_read on public.notifications for select to authenticated
      using (user_id = auth.uid());
  `);
  await apply('comment_notifications.sql');
  await apply('comment_notifications.sql');
  const notices = async () => (await db.query('select * from public.notifications')).rows;
  const clear = () => db.exec('delete from public.notifications');
  const recipients = async () => (await notices()).map(n => n.user_id).sort();
  const novelReply = (id, actor, parent = null) => db.query(
    'insert into public.review_replies(id,review_id,user_id,parent_reply_id,comment) values ($1,2,$2,$3,$4)',
    [id, actor, parent, 'A novel reply'],
  );
  const listId = (await db.query('select id from public.reading_lists where user_id=$1', [owner])).rows[0].id;
  await db.query("update public.reading_lists set visibility='public' where id=$1", [listId]);
  const listReview = (comment, actor = reader) => db.query(`
    insert into public.reading_list_reviews(reading_list_id,user_id,rating,comment)
    values ($1,$2,4,$3) on conflict (reading_list_id,user_id)
    do update set comment=excluded.comment, rating=excluded.rating returning id`, [listId, actor, comment]);
  let reviewId;
  const listReply = async (actor, parent = null) => (await db.query(`
    insert into public.reading_list_review_replies(review_id,user_id,parent_reply_id,comment)
    values ($1,$2,$3,'A list reply') returning id`, [reviewId, actor, parent])).rows[0].id;

  // No self-notice, then an authenticated writer delivers to somebody else's
  // inbox even though they have no notification INSERT policy.
  await novelReply(20, owner);
  assert.equal((await notices()).length, 0);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [reader]);
  await db.exec('set role authenticated');
  await assert.rejects(db.query(`insert into public.notifications(user_id,subject,body)
    values ($1,'Forged','Forged')`, [owner]), /row-level security/);
  await novelReply(21, reader);
  assert.equal((await notices()).length, 0, 'another reader cannot read the recipient inbox');
  assert.equal((await db.query("select has_function_privilege(current_user, 'public.notify_comment_activity()', 'execute') allowed")).rows[0].allowed, false);
  await db.exec('reset role');
  assert.deepEqual(await recipients(), [owner]);
  let notice = (await notices())[0];
  assert.equal(notice.type, 'comment_reply');
  assert.equal(notice.is_read, false);
  assert.equal(notice.data.novel_id, 2);
  assert.equal(notice.data.reply_id, 21);
  assert.match(notice.body, /Reader replied.*Another novel/);
  await clear();
  await novelReply(22, owner, 21);
  assert.deepEqual(await recipients(), [reader], 'nested reply targets immediate parent');
  await clear();
  await db.exec("update public.review_replies set comment='Edited' where id=22");
  await novelReply(23, reader, 21);
  await assert.rejects(db.query(`insert into public.review_replies(review_id,parent_reply_id,user_id,comment)
    values (999,21,$1,'Invalid')`, [owner]), /same review/);
  assert.equal((await notices()).length, 0);
  await db.exec('begin');
  await novelReply(24, reader);
  await db.exec('rollback');
  assert.equal((await notices()).length, 0, 'rolled-back comments leave no notice');

  // List upserts: ratings are silent; adding text notifies once, edits do not.
  reviewId = (await listReview(null)).rows[0].id;
  assert.equal((await notices()).length, 0);
  await listReview('First comment');
  assert.deepEqual(await recipients(), [owner]);
  notice = (await notices())[0];
  assert.equal(notice.type, 'reading_list_comment');
  assert.equal(notice.data.reading_list_id, listId);
  assert.equal(notice.data.owner_id, owner);
  await clear();
  await listReview('First comment');
  await listReview('Edited comment');
  await db.query('update public.reading_list_reviews set rating=5 where id=$1', [reviewId]);
  assert.equal((await notices()).length, 0);
  await listReview('New top-level comment', third);
  assert.deepEqual(await recipients(), [owner]);
  await clear();

  const reply = await listReply(third);
  assert.deepEqual(await recipients(), [owner, reader].sort());
  assert.deepEqual((await notices()).map(n => n.type).sort(), ['comment_reply', 'reading_list_comment']);
  await clear();
  const ownerReply = await listReply(owner, reply);
  assert.deepEqual(await recipients(), [third]);
  await clear();
  await listReply(reader, ownerReply);
  assert.deepEqual(await recipients(), [owner], 'owner/reply recipient is deduplicated');
  assert.equal((await notices())[0].type, 'comment_reply');
  await clear();
  await listReply(reader);
  assert.deepEqual(await recipients(), [owner], 'self-reply still informs list owner');
  await clear();
  await listReply(owner, ownerReply);
  assert.equal((await notices()).length, 0);

  // Former commenters must not learn new private or friends-only activity.
  await db.query("update public.reading_lists set visibility='private' where id=$1", [listId]);
  await listReply(owner);
  assert.equal((await notices()).length, 0);
  await db.query("update public.reading_lists set visibility='friends' where id=$1", [listId]);
  await db.query("insert into public.friendships values ($1,$2,'pending')", [reader, owner]);
  await listReply(owner);
  assert.equal((await notices()).length, 0);
  await db.exec("update public.friendships set status='accepted'");
  await listReply(owner);
  assert.deepEqual(await recipients(), [reader]);
  await clear();
  await db.query('update auth.users set raw_app_meta_data=$1::jsonb where id=$2', [JSON.stringify({axiom_banned: true}), reader]);
  await listReply(owner);
  await novelReply(25, reader); // Service writes also suppress banned senders.
  assert.equal((await notices()).length, 0);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [reader]);
  await db.exec('set role authenticated');
  await assert.rejects(novelReply(26, reader), /row-level security/);
  await db.exec('reset role');
  await db.query("update auth.users set raw_app_meta_data='{}' where id=$1", [reader]);

  // Delivery failure never loses a comment, and the second recipient still
  // receives their notice when delivery to the first recipient fails.
  await db.exec('alter table public.notifications add constraint fail_comment_delivery check (false)');
  await novelReply(27, reader);
  assert.equal((await db.query('select count(*)::int n from public.review_replies where id=27')).rows[0].n, 1);
  await db.exec('alter table public.notifications drop constraint fail_comment_delivery');
  await db.exec(`alter table public.notifications add constraint fail_owner_delivery check (user_id <> '${owner}')`);
  await listReply(third);
  assert.deepEqual(await recipients(), [reader]);
  await db.exec('alter table public.notifications drop constraint fail_owner_delivery');
  await clear();
  await db.exec('delete from public.reading_list_review_replies; delete from public.reading_list_reviews');
  await db.exec('delete from public.review_replies where id >= 20');
  assert.equal((await notices()).length, 0, 'deletes are silent');
}
